#!/usr/bin/env python3
"""Generate simple case mappings from the pinned Go Unicode tables.

Regenerating needs the Go 1.27.1 toolchain, whose GOROOT holds the Unicode
17.0.0 tables.
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
goroot = Path(subprocess.check_output(['go', 'env', 'GOROOT'], text=True).strip())
source = (goroot / 'src/unicode/tables.go').read_text()
version = re.search(r'const Version = "([^"]+)"', source).group(1)
assert version == '17.0.0', version
body = source.split('var _CaseRanges = []CaseRange{', 1)[1].split('\n}', 1)[0]
ranges = []
for lo, hi, upper, lower, title in re.findall(r'\{0x([0-9A-F]+), 0x([0-9A-F]+), d\{([^,]+), ([^,]+), ([^}]+)\}\}', body):
    delta = lambda text: 0x110000 if text == 'UpperLower' else int(text)
    ranges.append((int(lo, 16), int(hi, 16), delta(upper), delta(lower)))
assert len(ranges) > 300
assert all(a[1] < b[0] for a, b in zip(ranges, ranges[1:]))
# Typed mappings keep invalid Unicode out of the runtime representation.
output = '''// Copyright 2009 The Go Authors. All rights reserved.
// Use of this source code is governed by the BSD license in licenses/Go-BSD-3-Clause.txt.
// Generated by scripts/generate-casing.py from Go Unicode 17.0.0 tables.

pub(crate) fn map(c: char, upper: bool) -> char {
    if c.is_ascii() {
        return if upper { c.to_ascii_uppercase() } else { c.to_ascii_lowercase() };
    }
    let index = MAPPINGS.partition_point(|&(from, _, _)| from < c);
    MAPPINGS.get(index).filter(|&&(from, _, _)| from == c)
        .map_or(c, |&(_, up, down)| if upper { up } else { down })
}

const MAPPINGS: &[(char, char, char)] = &[
'''
mappings = 0
for low, high, up, down in ranges:
    for point in range(max(low, 128), high + 1):
        values = [point]
        for upper, delta in [(True, up), (False, down)]:
            mapped = low + ((point - low) & ~1) + int(not upper) if delta == 0x110000 else point + delta
            assert 0 <= mapped <= 0x10ffff and not 0xd800 <= mapped <= 0xdfff
            values.append(mapped)
        output += "    (" + ", ".join("'\\u{%x}'" % value for value in values) + "),\n"
        mappings += 1
output += "];\n"
path = ROOT / 'src/casing.rs'
path.write_text(output)
subprocess.run(['rustfmt', '--edition=2024', str(path)], check=True)
print(json.dumps({'version': version, 'ranges': len(ranges), 'mappings': mappings}))
